/**
 * Тип модуля.
 *
 * Названия пришли из кухни, но смысл общий: нижний ярус, верхний ярус,
 * колонна во всю высоту, отдельно стоящий объём, полка, техника.
 * Шкаф и тумба собираются из тех же типов — иначе пришлось бы дублировать
 * раскрой, спецификацию и расчёт крепежа на каждую категорию мебели.
 */
export type ModuleKind = 'base' | 'upper' | 'tall' | 'island' | 'shelf' | 'appliance'

/**
 * Модуль мебели в миллиметрах.
 * Начало координат — левый край помещения и уровень пола.
 */
export interface FurnitureModule {
  id: string
  kind: ModuleKind
  label: string
  /**
   * У какой стены стоит модуль.
   * Для основной стены x — отступ от левого края помещения.
   * Для боковой x — расстояние от задней стены вдоль боковой стены,
   * а глубина откладывается вдоль ширины помещения.
   */
  wall: 'main' | 'side'
  /** Отступ вдоль своей стены, мм. */
  x: number
  width: number
  /** Высота нижней кромки от пола, мм. */
  y: number
  height: number
  depth: number
  /** Число дверец или ящиков в модуле. */
  doors: number
  /** Материал и цвет фасада — для спецификации. */
  facade?: string
  /** Модуль в углу: другая присадка петель и другой доступ внутрь. */
  corner?: boolean
  /**
   * Модуль внутри другого корпуса — например, блок ящиков в секции шкафа.
   * У него нет ни ножек, ни цоколя: он опирается на чужие боковины.
   */
  internal?: boolean
  /**
   * Открытая секция без фасада. Это производственный факт, а не украшение
   * картинки: у неё нет ни дверцы, ни петель, ни ручки.
   */
  open?: boolean
  /**
   * Фронты — выдвижные ящики, а не распашные дверцы.
   * Ящику нужны направляющие, дверце — петли, и перепутать их нельзя.
   */
  drawers?: boolean
  /**
   * Как модуль держится: стоит на полу или висит на стене.
   * Подвесной тумбе нужны навесы и не нужны ни ножки, ни цоколь — в ванной
   * так делают почти всегда, чтобы мыть пол под мебелью.
   * Не задано — по типу модуля: верхние и полки висят, остальные стоят.
   */
  mounted?: 'floor' | 'wall'
  /**
   * Чем закрыт фронт, если это не обычный фасад: экран телевизора, зеркало,
   * керамика раковины. Нужен визуализации; в раскрое такие детали не участвуют.
   */
  surface?: 'screen' | 'mirror' | 'ceramic'
}

/**
 * Раскладка мебельного объекта: кухни, шкафа, тумбы.
 * Из неё выводятся чертежи, спецификация, крепёж и смета.
 */
export interface FurnitureLayout {
  room: { width: number; height: number; depth: number }
  /** Категория объекта: от неё зависит состав листов техпакета. */
  category: 'kitchen' | 'wardrobe' | 'cabinet' | 'tv_zone' | 'living_room' | 'hallway' | 'bathroom'
  /**
   * Есть ли столешница. У шкафа её нет, и лист «Схема столешниц» для него
   * не выпускается: пустой лист в цеху хуже отсутствующего.
   */
  hasWorktop: boolean
  counter: { height: number; depth: number; thickness: number }
  /** Границы фронта кухни вдоль основной стены, мм. */
  run: { start: number; end: number }
  /**
   * Фронт вдоль боковой стены, мм от задней стены.
   * null — кухня прямая. Начало отсчёта сдвинуто на глубину столешницы:
   * угол принадлежит основному фронту, иначе два корпуса встали бы в одно место.
   */
  sideRun: { start: number; end: number } | null
  backsplash: { top: number }
  /** Оконный проём на дальней стене, если он есть. */
  window: { x: number; width: number; y: number; height: number } | null
  modules: FurnitureModule[]
}
